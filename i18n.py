def set_language(language):
    global LANGUAGE
    LANGUAGE = "en" if language == "en" else "fr"


def tr(text):
    if LANGUAGE != "en":
        return text
    if text in EN:
        return EN[text]
    if text.isupper():
        for source, translated in EN.items():
            if source.upper() == text:
                return translated.upper()
    return text
